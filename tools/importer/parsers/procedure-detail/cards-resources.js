import { PDF_TO_FRAGMENT, DM_TO_FRAGMENT } from './resources-fragment-index.js';

/**
 * Parser for the Resources brochure grid
 * (.tabs .c-tabs .tabs-content .cols4 .colctrl on the source).
 *
 * The brochure cards duplicate content that ALREADY EXISTS in the project's card
 * fragments (content/fragments/card-*). So instead of inlining the cards, we
 * resolve each source brochure to its fragment and emit a `fragment` block that
 * loads it — the DRY authoring model the source library uses (see
 * content/us/en/ivs/resources).
 *
 * The match is AUTOMATIC, keyed on a stable invariant: the brochure's PDF href
 * (fallback: its Dynamic Media cover-image URL) is identical in the source card
 * and in the fragment, so resources-fragment-index.js (generated by
 * build-fragment-index.js) maps href -> fragment path. EN + ES sub-cards of the
 * same brochure resolve to one fragment, so matches are de-duplicated by path,
 * preserving first-appearance order.
 *
 * FALLBACK: a brochure with no matching fragment is kept as an inline
 * `Cards (resources)` card (nothing is ever lost), appended after the fragment
 * blocks. Header for that fallback block: "Cards (resources)".
 */

// Normalize an href/URL to the form used as an index key (decoded, no DM macro).
function pdfKey(href) {
  try { return decodeURI(href).trim(); } catch { return (href || '').trim(); }
}
function dmKey(url) {
  return (url || '').split('?')[0].trim();
}

// Resolve one brochure column to a fragment path via its PDF href, then its DM
// cover-image URL. Returns null when neither identifier is in the index.
function resolveFragment(col) {
  const learnMore = col.querySelector('a.btn[href], a.btn-teal[href], a[href$=".pdf"], a[href*=".pdf"]');
  const pdfHref = learnMore && learnMore.getAttribute('href');
  if (pdfHref) {
    const hit = PDF_TO_FRAGMENT[pdfKey(pdfHref)];
    if (hit) return hit;
  }
  const img = col.querySelector('.cta-img img, img');
  const imgSrc = img && (img.getAttribute('src') || img.getAttribute('title'));
  if (imgSrc) {
    const hit = DM_TO_FRAGMENT[dmKey(imgSrc)];
    if (hit) return hit;
  }
  return null;
}

// Build the inline fallback card cells for an unmatched brochure column (the
// original behaviour: bare DM image + a LEARN MORE button link).
function inlineCardCells(col, document) {
  const img = col.querySelector('.cta-img img, img');
  const learnMore = col.querySelector('a.btn[href], a.btn-teal[href]');
  const bodyCell = [];
  if (learnMore) {
    const label = learnMore.textContent.trim();
    learnMore.textContent = '';
    const strong = document.createElement('strong');
    strong.textContent = label;
    learnMore.append(strong);
    const p = document.createElement('p');
    p.append(learnMore);
    bodyCell.push(p);
  }
  return [img || '', bodyCell];
}

// Create a `fragment` block that references a fragment path.
function fragmentBlock(path, document) {
  const a = document.createElement('a');
  a.setAttribute('href', path);
  a.textContent = path;
  return WebImporter.Blocks.createBlock(document, { name: 'Fragment', cells: [[a]] });
}

export default function parse(element, { document }) {
  const cols = element.querySelectorAll(':scope > .row > [class*="col-"], .row > [class*="col-md-3"]');

  const fragmentPaths = []; // unique matched fragment paths, in first-seen order
  const inlineCells = []; // fallback cells for unmatched brochures

  cols.forEach((col) => {
    const img = col.querySelector('.cta-img img, img');
    const learnMore = col.querySelector('a.btn[href], a.btn-teal[href]');
    if (!img && !learnMore) return; // skip empty placeholder slots

    const fragmentPath = resolveFragment(col);
    if (fragmentPath) {
      if (!fragmentPaths.includes(fragmentPath)) fragmentPaths.push(fragmentPath);
    } else {
      inlineCells.push(inlineCardCells(col, document));
    }
  });

  if (fragmentPaths.length === 0 && inlineCells.length === 0) {
    element.replaceWith(...element.childNodes); // nothing authorable here
    return;
  }

  const out = fragmentPaths.map((p) => fragmentBlock(p, document));
  if (inlineCells.length) {
    out.push(WebImporter.Blocks.createBlock(document, { name: 'Cards (resources)', cells: inlineCells }));
  }
  element.replaceWith(...out);
}
