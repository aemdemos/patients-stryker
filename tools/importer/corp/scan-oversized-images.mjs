/*
 * Writes corp/oversized-images.js: the images of an import output that Edge Delivery cannot
 * preview (over 20 MB: AEM_BACKEND_DOC_IMAGE_TOO_BIG; DAM originals such as .psd / large .png,
 * Dynamic Media raw files at /is/content/), each with the smaller version the source has: AEM's
 * cq5dam.web.1280.1280 rendition of a DAM original, the image service (/is/image/) instead of a
 * Dynamic Media raw file — checked to exist and to be under the limit. A raw file that is an
 * animation becomes a still: they are listed for review.
 * Node script (not bundled).
 * usage: node tools/importer/corp/scan-oversized-images.mjs <content dir>
 */
import {
  readdirSync, readFileSync, statSync, writeFileSync,
} from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const LIMIT = 20 * 1024 * 1024;
const [dir] = process.argv.slice(2);
const urls = new Set();
(function walk(d) {
  readdirSync(d).forEach((f) => {
    const p = join(d, f);
    if (statSync(p).isDirectory()) { walk(p); return; }
    if (!p.endsWith('.plain.html')) return;
    const s = readFileSync(p, 'utf8');
    [...s.matchAll(/src="(https:\/\/(?:www\.stryker\.com\/content\/dam|media-assets\.stryker\.com\/is\/content)\/[^"]+)"/g)]
      .map((m) => m[1].replace(/&amp;/g, '&'))
      .filter((u) => !/\/renditions\/|\.thumb\.|\.m3u8|\.mp4|\.pdf/i.test(u))
      .forEach((u) => urls.add(u));
  });
}(dir));

const once = async (u) => {
  try {
    const h = await fetch(u, { method: 'HEAD', signal: AbortSignal.timeout(30000) });
    const len = Number(h.headers.get('content-length'));
    if (h.ok && len) return len;
    if (h.status === 404) return -404;
    const g = await fetch(u, { signal: AbortSignal.timeout(180000) });
    return g.ok ? (await g.arrayBuffer()).byteLength : -g.status;
  } catch {
    return -1;
  }
};
// (a failed lookup is tried again, three times in all; a missing file is not)
const failed = [];
const sizeOf = async (u, tries = 3) => {
  const size = await once(u);
  if (size > 0 || size === -404) return size;
  if (tries > 1) return sizeOf(u, tries - 1);
  failed.push(u);
  return -1;
};
const smaller = (u) => {
  if (u.includes('/is/content/')) return u.replace('/is/content/', '/is/image/');
  const ext = u.toLowerCase().split('?')[0].endsWith('.png') ? 'png' : 'jpeg';
  return `${u.split('?')[0]}/jcr:content/renditions/cq5dam.web.1280.1280.${ext}`;
};

const list = [...urls];
const big = [];
let i = 0;
// (8 lookups at a time: each worker takes the next URL until none is left)
const worker = async () => {
  if (i >= list.length) return;
  const u = list[i];
  i += 1;
  const size = await sizeOf(u);
  if (size > LIMIT) big.push([u, size]);
  await worker();
};
await Promise.all(Array.from({ length: 8 }, worker));

const map = {};
const checked = await Promise.all(big.sort().map(async ([u, size]) => {
  const alt = smaller(u);
  return [u, size, alt, await sizeOf(alt)];
}));
checked.forEach(([u, size, alt, altSize]) => {
  if (altSize > 0 && altSize < LIMIT) map[u] = alt;
  console.log(`${Math.round(size / 1048576)} MB ${u} → ${altSize > 0 ? `${Math.round(altSize / 1024)} KB ${alt}` : 'no smaller version'}`);
});
const out = join(dirname(fileURLToPath(import.meta.url)), 'oversized-images.js');
writeFileSync(out, `/*
 * Images over 20 MB (Edge Delivery cannot preview them: AEM_BACKEND_DOC_IMAGE_TOO_BIG) → the
 * smaller version the source has. Generated by scan-oversized-images.mjs from an import output
 * (${list.length} DAM originals and Dynamic Media raw files measured); do not edit by hand.
 */
export default {
${Object.entries(map).map(([k, v]) => `  '${k.replace(/'/g, "\\'")}':\n    '${v.replace(/'/g, "\\'")}',`).join('\n')}
};
`);
console.log(`${list.length} measured, ${big.length} over 20 MB, ${Object.keys(map).length} with a smaller version, ${failed.length} not measured → ${out}`);
failed.forEach((u) => console.log(`not measured: ${u}`));
