#!/usr/bin/env node
/* eslint-disable no-underscore-dangle, no-console */
/*
 * Build the resources fragment index used by the cards-resources parser.
 *
 * Scans the project's card fragments (content/fragments/card-*.plain.html) and
 * maps each brochure's STABLE identifiers — the brochure PDF href and the
 * Dynamic Media cover-image URL — to that fragment's path. The cards-resources
 * parser then matches a source page's brochure cards against this index by the
 * SAME identifiers and emits `fragment` block references instead of inlining the
 * cards. Because the match key is the (identical) brochure href, this is fully
 * automatic — no per-page hardcoding — and re-runnable whenever fragments change.
 *
 * Output: tools/importer/parsers/procedure-detail/resources-fragment-index.js
 * (a plain ES module the parser imports; esbuild inlines it into the bundle).
 *
 * Usage: node tools/importer/build-fragment-index.js
 */

import {
  readFileSync, writeFileSync, readdirSync,
} from 'fs';
import { dirname, resolve, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, '..', '..');
const FRAGMENTS_DIR = resolve(REPO, 'content/fragments');
const OUT = resolve(__dirname, 'parsers/procedure-detail/resources-fragment-index.js');

// Fragment DAM/media path prefixes we key on. The brochure PDF lives under
// /content/dam/…; the cover image is a media-assets.stryker.com DM URL.
const PDF_RE = /\/content\/dam\/[^"')\s]+\.pdf/gi;
const DM_RE = /https:\/\/media-assets\.stryker\.com\/is\/image\/stryker\/[^"')\s?]+/gi;

// Decode + strip DM sizing suffix so keys match regardless of the ?$max_width$ macro.
function normPdf(href) {
  try { return decodeURI(href).trim(); } catch { return href.trim(); }
}
function normDm(url) {
  return url.split('?')[0].trim();
}

function build() {
  const files = readdirSync(FRAGMENTS_DIR).filter((f) => /^card-.*\.plain\.html$/.test(f));
  const pdfIndex = {};
  const dmIndex = {};
  const fragments = [];

  files.forEach((file) => {
    const html = readFileSync(join(FRAGMENTS_DIR, file), 'utf8');
    const path = `/fragments/${file.replace(/\.plain\.html$/, '')}`;
    fragments.push(path);
    const pdfs = [...new Set((html.match(PDF_RE) || []).map(normPdf))];
    const dms = [...new Set((html.match(DM_RE) || []).map(normDm))];
    pdfs.forEach((p) => { pdfIndex[p] = path; });
    dms.forEach((d) => { dmIndex[d] = path; });
  });

  const header = [
    '/* eslint-disable */',
    '/**',
    ' * GENERATED by tools/importer/build-fragment-index.js — do not edit by hand.',
    ' * Maps a resources brochure\'s stable identifiers (PDF href, DM image URL) to',
    ' * the card fragment that contains it, so the cards-resources parser can emit',
    ' * fragment references automatically. Re-run the generator when fragments change.',
    ` * ${fragments.length} card fragment(s) indexed.`,
    ' */',
  ].join('\n');

  const body = `${header}\nexport const PDF_TO_FRAGMENT = ${JSON.stringify(pdfIndex, null, 2)};\n\n`
    + `export const DM_TO_FRAGMENT = ${JSON.stringify(dmIndex, null, 2)};\n`;

  writeFileSync(OUT, body);
  // eslint-disable-next-line no-console
  console.log(`[build-fragment-index] indexed ${fragments.length} fragment(s), `
    + `${Object.keys(pdfIndex).length} PDF key(s), ${Object.keys(dmIndex).length} DM key(s) -> ${OUT}`);
}

build();
