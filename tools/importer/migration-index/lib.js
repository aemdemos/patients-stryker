/**
 * Depth-first walk over the component tree in authored (JSON key) order.
 * visit(node, key, ctx) — ctx.area is the top-level content area, ctx.parents the
 * component ancestors. Property objects (cq:responsive, featuresCta, …) are walked too.
 */
export function forEachNode(root, visit) {
  const step = (node, key, ctx) => {
    if (!node || typeof node !== 'object' || Array.isArray(node)) return;
    visit(node, key, ctx);
    const next = isComponent(node) ? { ...ctx, parents: [...ctx.parents, node] } : ctx;
    Object.entries(node).forEach(([k, v]) => {
      if (k === 'cq:responsive') return;
      step(v, k, next.area ? next : { ...next, area: k });
    });
  };
  Object.entries(root).forEach(([k, v]) => step(v, k, { area: k, parents: [] }));
}

/** "Thu Sep 24 2026 17:56:29 GMT+0000" → "2026-09-24T17:56:29.000Z" (null if unparseable). */
export function toIso(value) {
  if (!value) return null;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? null : date.toISOString();
}

/** AEM page link → EDS path: /content/stryker/us/en/x(.html) → /us/en/x, …/index → …/ */
export function edsPagePath(ref) {
  const path = String(ref || '').replace(/^\/content\/stryker/, '').replace(/[?#].*$/, '').replace(/\.html$/, '');
  if (path === '/index' || path === '') return '/';
  return path.replace(/\/index$/, '/');
}

