/* ---------- minimal rich-text reader (AEM RTE output only) ---------- */

const BLOCK_TAGS = new Set(['h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'p', 'li', 'td', 'th', 'blockquote', 'div']);
const INLINE_FLAGS = new Set(['a', 'strong', 'b', 'em', 'i', 'u', 'sup', 'sub']);
const VOID_TAGS = new Set(['br', 'img', 'hr', 'wbr', 'input']);
const ENTITIES = {
  nbsp: ' ', amp: '&', quot: '"', lt: '<', gt: '>', apos: "'", rsquo: '’', lsquo: '‘', ldquo: '“', rdquo: '”', mdash: '—', ndash: '–', reg: '®', trade: '™', copy: '©',
};

function decode(text) {
  return text.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (m, e) => {
    if (e[0] === '#') return String.fromCodePoint(e[1].toLowerCase() === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
    return ENTITIES[e.toLowerCase()] ?? m;
  });
}

const attr = (attrs, name) => {
  const m = attrs.match(new RegExp(`\\s${name}\\s*=\\s*("([^"]*)"|'([^']*)')`, 'i'));
  return m ? (m[2] ?? m[3]) : '';
};

export const normColor = (c) => String(c || '').toLowerCase().replace(/\s+/g, '');

/**
 * Splits rich text into leaf runs: each non-blank text node with its formatting context.
 * @returns {{text, block, classes: string[], color: string, inline: string[]}[]}
 */
export function leafRuns(html) {
  const runs = [];
  const stack = [];
  [...String(html || '').matchAll(/<(\/?)([a-zA-Z][a-zA-Z0-9]*)([^>]*)>|([^<]+)/g)].forEach((m) => {
    const [, closing, rawTag, attrs, text] = m;
    if (text !== undefined) {
      const value = decode(text).replace(/\s+/g, ' ').trim();
      if (!value) return;
      const block = [...stack].reverse().find((e) => BLOCK_TAGS.has(e.tag));
      const classes = new Set();
      let color = '';
      const inline = new Set();
      stack.forEach((e) => {
        e.classes.forEach((c) => classes.add(c));
        if (e.color) color = e.color;
        if (INLINE_FLAGS.has(e.tag)) inline.add(e.tag === 'b' ? 'strong' : e.tag);
      });
      runs.push({
        text: value, block: block ? block.tag : 'none', classes: [...classes].sort(), color, inline: [...inline].sort(),
      });
      return;
    }
    const tag = rawTag.toLowerCase();
    if (VOID_TAGS.has(tag)) return;
    if (closing) {
      const at = stack.map((e) => e.tag).lastIndexOf(tag);
      if (at >= 0) stack.splice(at);
      return;
    }
    if (attrs.trim().endsWith('/')) return;
    const style = attr(attrs, 'style');
    const colorMatch = style.match(/(?:^|;)\s*color\s*:\s*([^;]+)/i);
    stack.push({
      tag,
      classes: attr(attrs, 'class').split(/\s+/).filter(Boolean),
      color: colorMatch ? normColor(colorMatch[1]) : '',
    });
  });
  return runs;
}
