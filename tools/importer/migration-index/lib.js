export function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
}

export const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));

/** /abs/.migration/xf-mapping/us/en/smart-care.json → /us/en/smart-care */
export function pagePathOf(file) {
  return `/${relative(PAGES_DIR, file).replace(/\.json$/, '')}`;
}

/** Every page export, in a stable order. */
export function loadPages() {
  return walk(PAGES_DIR).filter((f) => f.endsWith('.json')).sort()
    .map((file) => ({ path: pagePathOf(file), json: readJson(file) }));
}

export const isComponent = (node) => !!(node && typeof node === 'object' && node['sling:resourceType']);

