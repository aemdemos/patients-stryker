#!/usr/bin/env node
/* eslint-disable no-restricted-syntax, no-continue, no-console */
/* eslint-disable no-underscore-dangle, max-len */
/*
 * Auto-tier CSS fix generator.
 *
 * Turns the validator's auto-fixable style clusters into scoped CSS rules and
 * writes them into a MANAGED REGION of the target stylesheet (between marker
 * comments), so the block is fully regenerated each run — idempotent, never
 * duplicating or fighting hand-authored rules elsewhere in the file.
 *
 * Scoping is automatic from each cluster's page set + the report's auto-detected
 * fixTarget (see buildTarget):
 *   - a cluster on ALL pages    -> the whole-target scope (body.<template>)
 *   - a cluster on a SUBSET/ONE -> an OR-list of per-page body classes
 * combined with the run's own stable selector (href / block / section signal).
 *
 * SAFE fields (color, font-family, font-weight, font-style, text-decoration-line)
 * are applied by default — they encode "what the text is" and match the source
 * reliably. font-size is applied ONLY with --include-size, because on hand-edited
 * sources it is frequently responsive (viewport-relative) or inconsistent across
 * pages (the same element authored at different sizes); auto-pinning it would make
 * pages WORSE while satisfying the validator. Size clusters are left for a human.
 * line-height is treated the same way (a sizing field) and, when applied, is
 * emitted as the source's unitless ratio (e.g. `line-height: 1.15`).
 *
 * Breakpoint-specific clusters (present at only some measured widths) are never
 * auto-fixed: the report marks them `autoFixable: false` because an unconditional
 * rule would regress the widths where the text is already right.
 *
 * Usage (the fix-loop orchestrator resolves --css/--token-map for you):
 *   node tools/style-validator/fix-loop/apply-css-fixes.js \
 *     --report <report.json> \
 *     --css <target.css>              # template CSS or styles/themes.css
 *     --all-pages <name,name,...>     # page names from the validator config
 *     [--token-map <map.json>]        # optional: computed value -> var(--token)
 *     [--include-size]
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import { SIZE_FIELDS } from '../lib/style-fingerprint.js';

const BEGIN = '/* === AUTO-FIX (text-style-validator) — do not edit inside; regenerated by apply-css-fixes.js === */';
const END = '/* === END AUTO-FIX === */';

const SAFE_FIELDS = new Set(['color', 'fontFamily', 'fontWeight', 'fontStyle', 'textDecorationLine']);
const CSS_PROP = {
  color: 'color',
  fontFamily: 'font-family',
  fontWeight: 'font-weight',
  fontStyle: 'font-style',
  textDecorationLine: 'text-decoration',
  fontSize: 'font-size',
  lineHeight: 'line-height',
};

// Optional PROJECT design-token map: computed value (rgb() color or font-family
// name) -> the CSS custom property to emit instead of the literal, so generated
// fixes stay consistent with the target's design system. This is inherently
// project-specific, so it is NOT hardcoded — pass it via `--token-map <file>`
// (JSON: { "rgb(0, 0, 0)": "var(--color-black)", "Some Font W01":
// "var(--body-font-family)" }). With no map, the literal computed value is
// emitted (always correct, just not tokenized). Loaded in main() into `tokens`.
let tokens = [];

// Font-family aliasing (see --font-aliases / fontFamilyAliases in the config).
// The style delta stores the SOURCE site's raw family name (e.g. "Egyptienne for
// Stryker Light"), which the MIGRATED project frequently does NOT load — it
// bundles the same face under its own name (e.g. "URWEgyptienneW01-Light"). Left
// as-is, a generated `font-family: Egyptienne for Stryker Light` sets a font that
// doesn't exist here and silently falls back to serif — a broken "fix". So for a
// fontFamily fix we translate the source name to a family the project actually
// serves, via the alias map: source name → canonical alias → the migrated
// name(s) that share that alias. `familyAliases` is {rawName(lower): canonical}.
let familyAliases = {};
function canonicalFamily(raw) {
  const key = (raw || '').split(',')[0].replace(/["']/g, '').trim().toLowerCase();
  return familyAliases[key] || null;
}
// Reverse index: canonical alias -> the project (migrated) family names that map
// to it. Built in main() so a source family can be rewritten to the project's own.
let migratedByCanonical = {};

/**
 * Resolve the CSS value to emit for a field. For fontFamily, translate the source
 * raw name to a project-loadable family (token map first, then alias reverse-map);
 * returns null when it can't be safely resolved (caller then SKIPS the declaration
 * rather than emit an unloadable font).
 */
function toValue(field, raw) {
  if (field === 'textDecorationLine') return raw === 'none' ? 'none' : raw;
  // explicit token map wins for any field (colors, fonts)
  const hit = tokens.find(([v]) => v === raw || raw.startsWith(v));
  if (hit) return hit[1];
  if (field === 'fontFamily') {
    const canon = canonicalFamily(raw);
    const projectNames = canon ? migratedByCanonical[canon] : null;
    if (projectNames && projectNames.length) {
      // Emit the project's own family name(s) for this face, quoted.
      return projectNames.map((n) => (/\s/.test(n) ? `"${n}"` : n)).join(', ');
    }
    // Source family isn't aliased to anything the project loads → not safely
    // emittable. Signal the caller to skip this declaration (human review).
    return null;
  }
  return raw;
}

function parseArgs(argv) {
  const a = {};
  for (let i = 2; i < argv.length; i += 1) {
    if (argv[i].startsWith('--')) {
      const k = argv[i].slice(2);
      const v = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[(i += 1)] : true;
      a[k] = v;
    }
  }
  return a;
}

/** Scope prefix for a cluster: whole-target when it covers all pages, else an
 * OR-list of per-page body classes. The scoping is read from the report's
 * auto-detected fixTarget so it works for BOTH templated pages (body.<template>,
 * each page keyed by its own body/theme class) and singletons (body.<theme>).
 *   - target.allScope   : the "covers every page" selector (e.g. body.<template>)
 *   - target.pageScope  : fn(pageName) → that page's own body class selector
 */
function scopePrefixes(cluster, allPages, target) {
  const pages = cluster.pageSlugs || cluster.pages || [];
  const coversAll = allPages.length && pages.length >= allPages.length
    && allPages.every((p) => pages.includes(p));
  if (coversAll && target.allScope) return [`${target.allScope} main`];
  return pages.map((slug) => `${target.pageScope(slug)} main`);
}

// Build the scoping model from the report's fixTarget + pageMeta:
//   template → body.<template> for all-page clusters, body.<page-theme> per page;
//   theme    → body.<page-theme> per page (singletons, no all-page scope).
// Throws for 'none'/'mixed' (no safe scope — see below).
function buildTarget(report) {
  const ft = report.fixTarget || {};
  const metaByPage = {};
  (report.pageMeta || []).forEach((m) => { metaByPage[m.page] = m; });
  if (ft.kind === 'template' && ft.name) {
    return {
      allScope: `body.${ft.name}`,
      // A cluster on a SUBSET of pages is scoped per page via that page's own
      // theme class (a per-page body class the import stamps as page metadata,
      // enabling targeted per-page fixes without a bespoke selector). Falls back
      // to the page name when a page declares no theme.
      pageScope: (page) => `body.${(metaByPage[page] && metaByPage[page].theme) || page}`,
    };
  }
  if (ft.kind === 'theme') {
    // Singleton(s): each page scoped to its own theme class; no "all" scope.
    return {
      allScope: null,
      pageScope: (page) => `body.${(metaByPage[page] && metaByPage[page].theme) || page}`,
    };
  }
  // No detectable template/theme (fixTarget kind 'none' or 'mixed') — there is no
  // safe body scope to write generated rules under, so refuse rather than guess.
  throw new Error(`apply-css-fixes: cannot scope fixes — report fixTarget.kind="${ft.kind || 'unknown'}". Each page needs a template or theme in its metadata.`);
}

function buildRule(cluster, allPages, includeSize, target) {
  const decls = [];
  const skippedDecls = [];
  for (const d of cluster.delta) {
    if (SIZE_FIELDS.has(d.field)) {
      if (!includeSize) continue;
      // lineHeight's delta source is already a unitless ratio (e.g. "1.15").
      const v = d.field === 'lineHeight' ? d.source : toValue(d.field, d.source);
      decls.push(`  ${CSS_PROP[d.field]}: ${v};`);
      continue;
    }
    if (!SAFE_FIELDS.has(d.field)) continue;
    const value = toValue(d.field, d.source);
    // toValue returns null for a fontFamily we can't map to a project-loadable
    // family — skip it (never emit an unloadable source font name that would
    // silently fall back to serif). Recorded so main() can report it.
    if (value == null) { skippedDecls.push(d); continue; }
    decls.push(`  ${CSS_PROP[d.field]}: ${value};`);
  }
  if (skippedDecls.length) cluster.__skippedDecls = skippedDecls;
  if (!decls.length) return null; // nothing safe to apply (e.g. size-only w/o flag)
  // Prefer STABLE selectors (href/id anchors, or class-scoped) and drop fragile
  // ones (a bare `u`/`b`/`i`/`span`/`em`/`strong` tag is a styling-artifact
  // element, not a durable target) — but only when a stable one exists for the
  // cluster, so we never end up with an empty rule.
  const isFragile = (s) => /(^|\s)(u|b|i|em|strong|span)$/.test(s);
  const chosen = cluster.selectors.filter((s) => !isFragile(s));
  // Only fragile/artifact selectors (e.g. a bare <u>) → not safely auto-fixable;
  // skip and let it be reported for human review rather than chase the artifact.
  if (!chosen.length) return null;
  const prefixes = scopePrefixes(cluster, allPages, target);
  const selectors = [];
  for (const pfx of prefixes) {
    for (const sel of chosen) selectors.push(`${pfx} ${sel}`);
  }
  if (!selectors.length) return null;
  const sample = cluster.samples && cluster.samples[0];
  const comment = `  /* ${cluster.key}${sample ? ` — e.g. "${sample.text.slice(0, 40)}"` : ''} */`;
  return `${selectors.join(',\n')} {\n${comment}\n${decls.join('\n')}\n}`;
}

function main() {
  const args = parseArgs(process.argv);
  const report = JSON.parse(readFileSync(resolve(args.report || 'migration-work/importer/text-style-diff.json'), 'utf8'));
  // Target CSS file is required (no project default): the orchestrator resolves it
  // from the report's auto-detected fixTarget (template CSS or styles/themes.css).
  if (!args.css) throw new Error('apply-css-fixes: --css <target.css> is required (template CSS or styles/themes.css).');
  const cssPath = resolve(args.css);
  const allPages = (args['all-pages'] || '').split(',').map((s) => s.trim()).filter(Boolean);
  const includeSize = !!args['include-size'];
  // Optional design-token map (see toValue). JSON object: literal -> var(--token).
  if (args['token-map']) {
    const map = JSON.parse(readFileSync(resolve(args['token-map']), 'utf8'));
    tokens = Object.entries(map);
  }
  // Font-family aliases (source/migrated names that denote the SAME face). Used to
  // rewrite a source font name to the project's own loadable family. Accepts a
  // JSON file { "Raw Name": "canonical", ... } via --font-aliases; the orchestrator
  // derives this from the config's fontFamilyAliases.
  if (args['font-aliases']) {
    const raw = JSON.parse(readFileSync(resolve(args['font-aliases']), 'utf8'));
    familyAliases = {};
    for (const [k, v] of Object.entries(raw)) familyAliases[k.toLowerCase()] = v;
    // Reverse index: canonical -> project family names. The MIGRATED side of each
    // style delta already carries a project-loadable family, so learn the project
    // name for each canonical alias from the report's own migrated fingerprints.
    migratedByCanonical = {};
    for (const c of report.clusters || []) {
      for (const s of c.samples || []) {
        const mf = s.migratedFingerprint && s.migratedFingerprint.fontFamily;
        const canon = canonicalFamily(mf);
        if (!canon) continue;
        const name = (mf || '').split(',')[0].replace(/["']/g, '').trim();
        if (!migratedByCanonical[canon]) migratedByCanonical[canon] = [];
        if (!migratedByCanonical[canon].includes(name)) migratedByCanonical[canon].push(name);
      }
    }
  }

  const target = buildTarget(report);
  const auto = (report.clusters || []).filter((c) => c.autoFixable);
  const rules = [];
  const applied = [];
  const skipped = [];
  for (const c of auto) {
    const rule = buildRule(c, allPages, includeSize, target);
    if (rule) { rules.push(rule); applied.push(c.key); } else skipped.push(c.key);
  }

  const header = [
    '/* Generated from the text-style validator. Safe fields (color/family/weight/',
    '   style/decoration) auto-applied; font-size only with --include-size. Re-run',
    '   apply-css-fixes.js to regenerate; edit clusters/source, not this block. */',
  ].join('\n');
  const block = [BEGIN, header, ...rules, END].join('\n\n');

  let css = readFileSync(cssPath, 'utf8');
  const begIdx = css.indexOf(BEGIN);
  if (begIdx >= 0) {
    const endIdx = css.indexOf(END, begIdx);
    css = `${css.slice(0, begIdx)}${block}${css.slice(endIdx + END.length)}`;
  } else {
    css = `${css.trimEnd()}\n\n${block}\n`;
  }
  writeFileSync(cssPath, css);

  console.log(`[apply-css] wrote ${rules.length} rule(s) into ${cssPath}`);
  if (applied.length) console.log(`  applied: \n    - ${applied.join('\n    - ')}`);
  if (skipped.length) console.log(`  skipped (size-only without --include-size, or no safe field): \n    - ${skipped.join('\n    - ')}`);
  // Font-family declarations dropped because the source family couldn't be mapped
  // to a project-loadable name (no alias/token match) — surfaced for human review
  // (usually a re-tag better fixed in the parser/authoring, or a missing alias).
  const skippedFonts = auto
    .filter((c) => c.__skippedDecls && c.__skippedDecls.some((d) => d.field === 'fontFamily'))
    .map((c) => `${c.key} (source font "${c.__skippedDecls.find((d) => d.field === 'fontFamily').source}" not mapped to a project family)`);
  if (skippedFonts.length) {
    console.log(`  NOTE: ${skippedFonts.length} font-family fix(es) skipped — unmappable source font (add a fontFamilyAlias or fix at the parser):\n    - ${skippedFonts.join('\n    - ')}`);
  }
  const sizeOnly = auto.filter((c) => c.delta.every((d) => SIZE_FIELDS.has(d.field))).map((c) => c.key);
  if (sizeOnly.length && !includeSize) {
    console.log(`  NOTE: ${sizeOnly.length} size-only cluster(s) left for human review (responsive / inconsistent-in-source).`);
  }
}

main();
